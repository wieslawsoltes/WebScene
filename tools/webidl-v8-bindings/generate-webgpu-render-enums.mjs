import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import crypto from 'node:crypto';
import * as webidl from 'webidl2';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const contract=JSON.parse(fs.readFileSync(path.join(root,'docs/graphics/webgpu-v8-contract.json'),'utf8'));
const source=fs.readFileSync(new URL('./node_modules/@webref/idl/webgpu.idl',import.meta.url),'utf8');
if(crypto.createHash('sha256').update(source).digest('hex')!==contract.sha256)throw new Error('WebGPU IDL pin mismatch');
const idl=webidl.parse(source);
// Explicit reviewed native spellings; never expose Dawn-only enum values.
const mappings=JSON.parse(fs.readFileSync(new URL('./webgpu-render-enums.json',import.meta.url),'utf8'));
let output=`// Generated by tools/webidl-v8-bindings/generate-webgpu-render-enums.mjs.
// @webref/idl ${contract.version}; SHA256 ${contract.sha256}
#pragma once
#include <webgpu/webgpu_cpp.h>
#include <array>
#include <string_view>
#include <utility>
namespace webscene::graphics {
template<class Native> struct webgpu_enum_names;
`;
for(const [name,mapping] of Object.entries(mappings)) {
 const values=idl.find(x=>x.type==='enum'&&x.name==='GPU'+name).values.map(x=>x.value);
 if(JSON.stringify(values)!==JSON.stringify(Object.keys(mapping)))throw new Error(`${name} mapping requires review`);
 output+=`template<> struct webgpu_enum_names<wgpu::${name}> {
    static inline constexpr std::array<std::pair<std::string_view,wgpu::${name}>,${values.length}> values{{
${values.map(value=>`        {"${value}",wgpu::${name}::${mapping[value]}},`).join('\n')}
    }};
};
`;
}
output+='} // namespace webscene::graphics\n';
const destination=path.join(root,'experiments/WebScene.NativeEngine.Probe/native/graphics/webgpu_render_enums.h');
if(process.argv.includes('--check')) {
 if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8')!==output)throw new Error('WebGPU render enum catalog is stale');
}else fs.writeFileSync(destination,output);
