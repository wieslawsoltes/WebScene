import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import crypto from 'node:crypto';
import * as webidl from 'webidl2';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const contract=JSON.parse(fs.readFileSync(path.join(root,'docs/graphics/webgpu-v8-contract.json'),'utf8'));
const source=fs.readFileSync(new URL('./node_modules/@webref/idl/webgpu.idl',import.meta.url),'utf8');
if(crypto.createHash('sha256').update(source).digest('hex')!==contract.sha256) throw new Error('WebGPU IDL pin mismatch');
const names=webidl.parse(source).find(x=>x.type==='enum'&&x.name==='GPUFeatureName').values.map(x=>x.value);
// Explicit spellings keep acronym changes and new IDL values reviewable.
const native=['CoreFeaturesAndLimits','DepthClipControl','Depth32FloatStencil8','TextureCompressionBC','TextureCompressionBCSliced3D','TextureCompressionETC2','TextureCompressionASTC','TextureCompressionASTCSliced3D','TimestampQuery','IndirectFirstInstance','ShaderF16','RG11B10UfloatRenderable','BGRA8UnormStorage','Float32Filterable','Float32Blendable','ClipDistances','DualSourceBlending','Subgroups','TextureFormatsTier1','TextureFormatsTier2','PrimitiveIndex','TextureComponentSwizzle','SubgroupSizeControl'];
if(names.length!==native.length) throw new Error('GPUFeatureName mapping requires review');
const output=`// Generated by tools/webidl-v8-bindings/generate-webgpu-features.mjs.
// @webref/idl ${contract.version}; webgpu.idl SHA256 ${contract.sha256}
#pragma once
#include <webgpu/webgpu_cpp.h>
#include <array>
#include <optional>
#include <string_view>
#include <stdexcept>
#include <vector>

namespace webscene::graphics {
struct webgpu_feature_name { std::string_view name; wgpu::FeatureName native; };
inline constexpr std::array<webgpu_feature_name,${names.length}> webgpu_feature_names{{
${names.map((name,i)=>`    {"${name}",wgpu::FeatureName::${native[i]}},`).join('\n')}
}};
inline std::optional<wgpu::FeatureName> webgpu_feature_from_name(std::string_view name) {
    for (const auto& feature:webgpu_feature_names) if (feature.name==name) return feature.native;
    return std::nullopt;
}
inline std::optional<std::string_view> webgpu_feature_to_name(wgpu::FeatureName native) {
    for (const auto& feature:webgpu_feature_names) if (feature.native==native) return feature.name;
    return std::nullopt;
}
// Both Adapter and Device implement HasFeature. Device features are the enabled
// subset, not the adapter's full capabilities. Never enumerate native extensions
// into the browser surface, even when the host enables them for shared images.
template<class Source> std::vector<std::string_view> webgpu_supported_feature_names(const Source& source) {
    if (!source) throw std::invalid_argument("WebGPU feature source is null");
    std::vector<std::string_view> result;
    for (const auto& feature:webgpu_feature_names)
        if (source.HasFeature(feature.native)) result.push_back(feature.name);
    return result;
}
} // namespace webscene::graphics
`;
const destination=path.join(root,'experiments/WebScene.NativeEngine.Probe/native/graphics/webgpu_feature_names.h');
if(process.argv.includes('--check')) {
    if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8')!==output) throw new Error('WebGPU feature catalog is stale');
} else fs.writeFileSync(destination,output);
