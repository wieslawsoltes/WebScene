import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import crypto from 'node:crypto';
import * as webidl from 'webidl2';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const contract=JSON.parse(fs.readFileSync(path.join(root,'docs/graphics/webgpu-v8-contract.json'),'utf8'));
const source=fs.readFileSync(new URL('./node_modules/@webref/idl/webgpu.idl',import.meta.url),'utf8');
if(crypto.createHash('sha256').update(source).digest('hex')!==contract.sha256) throw new Error('WebGPU IDL pin mismatch');
const members=webidl.parse(source).find(x=>x.type==='interface'&&x.name==='GPUSupportedLimits').members;
for(const member of members) if(member.type!=='attribute'||!member.readonly||!['unsigned long','unsigned long long'].includes(member.idlType.idlType)) throw new Error('Supported limit mapping requires review');
const compatibility=new Set(["maxStorageBuffersInVertexStage","maxStorageBuffersInFragmentStage","maxStorageTexturesInVertexStage","maxStorageTexturesInFragmentStage"]);
const output=`// Generated by tools/webidl-v8-bindings/generate-webgpu-limits.mjs.
// @webref/idl ${contract.version}; webgpu.idl SHA256 ${contract.sha256}
#pragma once
#include <webgpu/webgpu_cpp.h>
#include <array>
#include <string_view>
#include <variant>
#include <limits>
#include <type_traits>
namespace webscene::graphics {
struct webgpu_limit_name {
    std::u16string_view name;
    std::variant<uint32_t wgpu::Limits::*,uint64_t wgpu::Limits::*,uint32_t wgpu::CompatibilityModeLimits::*> member;
    uint64_t read(const wgpu::Limits& limits,const wgpu::CompatibilityModeLimits& compatibility) const {
        return std::visit([&](auto field) {
            if constexpr (std::is_same_v<decltype(field),uint32_t wgpu::CompatibilityModeLimits::*>) return uint64_t(compatibility.*field);
            else return uint64_t(limits.*field);
        },member);
    }
    // Reject values that cannot be represented, including Dawn's undefined
    // sentinel. Never let a requested integer silently become an omitted limit.
    bool write(wgpu::Limits& limits,wgpu::CompatibilityModeLimits& compatibility,uint64_t value) const {
        return std::visit([&](auto field) {
            if constexpr (std::is_same_v<decltype(field),uint32_t wgpu::CompatibilityModeLimits::*>) {
                if (value>=UINT32_MAX) return false;
                compatibility.*field=static_cast<uint32_t>(value); return true;
            } else {
                using T=std::remove_reference_t<decltype(limits.*field)>;
                if (value>=std::numeric_limits<T>::max()) return false;
                limits.*field=static_cast<T>(value); return true;
            }
        },member);
    }
};
inline const std::array<webgpu_limit_name,${members.length}> webgpu_limit_names{{
${members.map(x=>`    {u"${x.name}",&wgpu::${compatibility.has(x.name)?"CompatibilityModeLimits":"Limits"}::${x.name}},`).join('\n')}
}};
inline const webgpu_limit_name* webgpu_limit_from_name(std::u16string_view name) {
    for (const auto& limit:webgpu_limit_names) if (limit.name==name) return &limit;
    return nullptr;
}
} // namespace webscene::graphics
`;
const destination=path.join(root,'experiments/WebScene.NativeEngine.Probe/native/graphics/webgpu_limit_names.h');
if(process.argv.includes('--check')) {
    if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8')!==output) throw new Error('WebGPU limit catalog is stale');
} else fs.writeFileSync(destination,output);
